// PDF report generation helper for Nume calculation, graphing, equation, and conversion outputs
export const downloadCalculationPdf = (expression: string, result: string) => {
  generatePdfReport("Calculation Report", [
    `Expression: ${expression}`,
    `Result: ${result}`,
    `Generated by Nume: Scientific Calculator Pro`,
  ]);
};

export const downloadGraphPdf = (fn: string, pointsCount: number) => {
  generatePdfReport("Graph Analysis Report", [
    `Function: f(x) = ${fn}`,
    `Sampled Points: ${pointsCount}`,
    `Generated by Nume Graphing Suite`,
  ]);
};

export const downloadEquationPdf = (equation: string, solution: string) => {
  generatePdfReport("Equation Solver Report", [
    `Equation: ${equation}`,
    `Solution / Roots: ${solution}`,
    `Generated by Nume Equation Solver`,
  ]);
};

export const downloadConversionPdf = (fromValue: string, fromUnit: string, toValue: string, toUnit: string) => {
  generatePdfReport("Unit Conversion Report", [
    `Converted: ${fromValue} ${fromUnit} = ${toValue} ${toUnit}`,
    `Generated by Nume Converter Suite`,
  ]);
};

const generatePdfReport = (title: string, lines: string[]) => {
  const html = `
    <!DOCTYPE html>
    <html>
      <head>
        <title>${title}</title>
        <style>
          body { font-family: Helvetica, Arial, sans-serif; padding: 40px; color: #111; }
          h1 { color: #7c3aed; border-bottom: 2px solid #7c3aed; padding-bottom: 10px; }
          .line { font-size: 16px; margin: 15px 0; }
          .footer { margin-top: 40px; font-size: 12px; color: #666; border-top: 1px solid #ddd; padding-top: 10px; }
        </style>
      </head>
      <body>
        <h1>Nume — ${title}</h1>
        ${lines.map((l) => `<div class="line">${l}</div>`).join("")}
        <div class="footer">Exported on ${new Date().toLocaleString()} from Nume: Scientific Calculator Pro.</div>
        <script>
          window.print();
        </script>
      </body>
    </html>
  `;
  const blob = new Blob([html], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const win = window.open(url, "_blank");
  if (win) {
    win.focus();
  }
};
